"""Generate an ID-only quest-drop baseline from pinned pfQuest Vanilla inputs.

Requires Lupa's Lua 5.1 runtime only for generation, never in the installed addon.
Download the files named in tools/data/pfquest-source.json at its exact revision
into --source-directory, retaining their db/ paths. This tool does not download.
"""
import argparse
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]


def validate_review_pins(manifest, review):
    if not review.get("retain_existing_baseline"):
        raise ValueError("This baseline has not been retained by the maintainer")
    if manifest["revision"] != review["pfquest"]["revision"] or \
            manifest["upstream"]["revision"] != review["vmangos"]["revision"]:
        raise ValueError("Source revision changed; update the licensing review before generation")


def notice_hash(data):
    # Git may check text notices out with CRLF on Windows. Hash the same LF
    # text that the release packager ships; source database hashes stay raw.
    return hashlib.sha256(data.replace(b"\r\n", b"\n")).hexdigest()


def positive_ids(values):
    result = sorted(set(values))
    if any(type(value) is not int or value <= 0 for value in result):
        raise ValueError("Entity IDs must be positive integers")
    return result


def project(pf):
    items = pf["items"]["data"]
    refs = pf["refloot"]["data"]
    quest_items, item_npcs = {}, {}
    for quest_id, quest in pf["quests"]["data"].items():
        objectives = quest["obj"]
        required = objectives and objectives["I"]
        if required is None:
            continue
        ids = positive_ids(required.values())
        has_drop = False
        for item_id in ids:
            item = items[item_id]
            if item is None:
                continue
            drops = set(item["U"].keys()) if item["U"] else set()
            if item["R"]:
                for ref_id in item["R"].keys():
                    ref = refs[ref_id]
                    if ref is not None and ref["U"]:
                        drops.update(ref["U"].keys())
            # Vendor, container, object, fishing and skinning relationships
            # are not hostile NPC loot sources for these nameplate markers.
            if item["V"]:
                drops.difference_update(item["V"].keys())
            if drops:
                item_npcs[item_id] = positive_ids(drops)
                has_drop = True
        if has_drop:
            # Keep non-drop objectives too. Omitting them would make a mixed
            # quest look like an unambiguous single-item quest at runtime.
            quest_items[quest_id] = ids
    return quest_items, item_npcs


def used_items(quests, items):
    used = {item for required in quests.values() for item in required}
    return quests, {key: value for key, value in items.items() if key in used and value}


def render(quests, items, revision):
    lines = [
        "-- Generated by tools/build_quest_drops.py from pinned pfQuest Vanilla inputs.",
        "-- pfQuest MIT and upstream VMaNGOS GPL v2 notices: see Licenses/QuestDropData-NOTICES.txt.",
        f"-- Source revision: {revision}",
        "-- Vanilla baseline only; no Wowhead overrides or validated Forever corrections.",
        "local _, VV = ...", "VV.Nameplates.QuestDropData = {",
        "    reviewed = {},",
        "    quests = {",
    ]
    for name, table in (("quests", quests), ("items", items)):
        if name == "items":
            lines.append("    items = {")
        for ident, values in sorted(table.items()):
            lines.append(f"        [{ident}] = {{{', '.join(map(str, values))}}},")
        lines.append("    },")
    lines.extend(["}", ""])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-directory", type=Path, required=True)
    parser.add_argument("--lua-runtime", type=Path)
    parser.add_argument("--check", action="store_true", help="Verify generated data without writing")
    args = parser.parse_args()
    manifest = json.loads((ROOT / "tools/data/pfquest-source.json").read_text())
    review = json.loads((ROOT / "tools/data" / manifest["licensing_review"]).read_text())
    validate_review_pins(manifest, review)
    for name, expected_hash in manifest["license_sha256"].items():
        if notice_hash((ROOT / name).read_bytes()) != expected_hash:
            raise SystemExit(f"License notice checksum mismatch: {name}")
    if args.lua_runtime:
        sys.path.insert(0, str(args.lua_runtime.resolve()))
    from lupa.lua51 import LuaRuntime
    lua = LuaRuntime(max_memory=256 * 1024 * 1024)
    env = lua.eval('{pfDB={quests={}, items={}, refloot={}}}')
    load = lua.eval('function(text, env) local fn=assert(loadstring(text)); setfenv(fn, env); fn() end')
    for name, expected_hash in manifest["files"].items():
        data = (args.source_directory / name).read_bytes()
        if hashlib.sha256(data).hexdigest() != expected_hash:
            raise SystemExit(f"Source checksum mismatch: {name}")
        # Empty environment: these pinned inputs define data tables only.
        load(data.decode("utf-8"), env)
    quests, items = used_items(*project(env["pfDB"]))
    output = ROOT / "Modules/Nameplates/QuestDropData.lua"
    text = render(quests, items, manifest["revision"])
    if args.check:
        if output.read_text(encoding="utf-8") != text:
            raise SystemExit("QuestDropData.lua differs; regenerate and review it")
    else:
        output.write_text(text, encoding="utf-8", newline="\n")
    print(f"{'Verified' if args.check else 'Generated'} {len(quests):,} quests, "
          f"{len(items):,} items, {sum(map(len, items.values())):,} NPC links; "
          f"{len(text.encode('utf-8')):,} bytes")


if __name__ == "__main__":
    main()
